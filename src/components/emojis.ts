/** Minuscules sans accents, pour une recherche tolérante (« fete » trouve « fête »). */
export function normalizeSearch(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .trim();
}

const ALL = EMOJI_GROUPS.flatMap((g) => g.list.map(([e, k]) => ({ e, k: normalizeSearch(`${g.name} ${k}`) })));

/** Emojis dont un mot-clé commence par chaque mot cherché, sans doublon. */
export function searchEmojis(query: string): string[] {
  const words = normalizeSearch(query).split(/\s+/).filter(Boolean);
  if (words.length === 0) return [];
  const seen = new Set<string>();
  const out: string[] = [];
  for (const { e, k } of ALL) {
    const keys = k.split(/[\s'-]+/);
    if (words.every((w) => keys.some((key) => key.startsWith(w))) && !seen.has(e)) {
      seen.add(e);
      out.push(e);
    }
  }
  return out;
}
